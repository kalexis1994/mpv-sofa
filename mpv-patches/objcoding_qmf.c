/* Pre-computed twiddle factors for analysis and synthesis DFTs.
 * Lazily initialized on first use. */
static int qmf_tables_inited = 0;
static float ana_cos[64][128];  /* cos(pi*(sb+0.5)*(j-0.5)/64) */
static float ana_sin[64][128];  /* sin(pi*(sb+0.5)*(j-0.5)/64) */
static float syn_cos[128][64];  /* for synthesis: cos(pi/(4*n)*(2*sb+1)*(2*j-2*n-1)) */
static float syn_sin[128][64];  /* sin component (used to extract real part) */

static void qmf_init_tables(void) {
    if (qmf_tables_inited) return;
    const int n = OBJCODING_QMF_N;

    /* Analysis twiddles: exp(i*pi*(sb+0.5)*(j-0.5)/n) */
    for (int sb = 0; sb < n; sb++) {
        for (int j = 0; j < 2 * n; j++) {
            double angle = M_PI * (sb + 0.5) * (j - 0.5) / n;
            ana_cos[sb][j] = (float)cos(angle);
            ana_sin[sb][j] = (float)sin(angle);
        }
    }

    /* Synthesis twiddles: exp(i*pi/(4*n)*(2*sb+1)*(2*j-2*n-1)) */
    for (int j = 0; j < 2 * n; j++) {
        for (int sb = 0; sb < n; sb++) {
            double angle = M_PI / (4.0 * n) * (2 * sb + 1) * (2 * j - 2 * n - 1);
            syn_cos[j][sb] = (float)cos(angle);
            syn_sin[j][sb] = (float)sin(angle);
        }
    }

    qmf_tables_inited = 1;
}

void objcoding_qmf_analysis_init(ObjCodingQmfAnalysis *a) {
    memset(a->state, 0, sizeof(a->state));
    qmf_init_tables();
}

void objcoding_qmf_synthesis_init(ObjCodingQmfSynthesis *s) {
    memset(s->state, 0, sizeof(s->state));
    qmf_init_tables();
}

/*
 * Analysis: 64 PCM samples → 64 complex subband values
 * Pseudocodes 8-12 from ETSI TS 103 420
 */
void objcoding_qmf_analyze(ObjCodingQmfAnalysis *a, const float *pcm_64,
                      float out_re[OBJCODING_QMF_N], float out_im[OBJCODING_QMF_N])
{
    const int n = OBJCODING_QMF_N;          /* 64 */
    const int flen = OBJCODING_QMF_LEN;    /* 640 */
    float *st = a->state;

    /* Pseudocode 8: shift state right by n */
    memmove(st + n, st, (flen - n) * sizeof(float));

    /* Pseudocode 9: insert new samples (reversed) */
    for (int j = 0; j < n; j++)
        st[j] = pcm_64[n - 1 - j];

    /* Pseudocode 10: window */
    float z[OBJCODING_QMF_LEN];
    for (int j = 0; j < flen; j++)
        z[j] = st[j] * prot64[j];

    /* Pseudocode 11: fold (640 → 128) */
    float u[128];
    for (int j = 0; j < 2 * n; j++) {
        u[j] = 0;
        for (int k = 0; k < flen / (2 * n); k++)  /* k = 0..4 */
            u[j] += z[j + k * 2 * n];
    }

    /* Pseudocode 12: complex DFT using pre-computed twiddles */
    for (int sb = 0; sb < n; sb++) {
        float re = 0, im = 0;
        for (int j = 0; j < 2 * n; j++) {
            re += u[j] * ana_cos[sb][j];
            im += u[j] * ana_sin[sb][j];
        }
        out_re[sb] = re;
        out_im[sb] = im;
    }
}

/*
 * Synthesis: 64 complex subband values → 64 PCM samples
 * Pseudocodes 13-17 from ETSI TS 103 420
 */
void objcoding_qmf_synthesize(ObjCodingQmfSynthesis *s, const float re[OBJCODING_QMF_N],
                         const float im[OBJCODING_QMF_N], float pcm_out[OBJCODING_QMF_N])
{
    const int n = OBJCODING_QMF_N;          /* 64 */
    const int flen = OBJCODING_QMF_LEN;    /* 640 */
    float *st = s->state;
    int st_len = 2 * flen;           /* 1280 */

    /* Pseudocode 13: shift state right by 2*n */
    memmove(st + 2 * n, st, (st_len - 2 * n) * sizeof(float));

    /* Pseudocode 14: compute 2*n new samples via inverse DFT
     * qsyn_filt[j] = sum_{sb} real(Q[sb]/n * exp(i*pi/(4n)*(2sb+1)*(2j-2n-1)))
     * where Q[sb] = re[sb] + i*im[sb]
     * real(Q/n * exp(i*angle)) = (re*cos - im*sin) / n */
    for (int j = 0; j < 2 * n; j++) {
        float sum = 0;
        for (int sb = 0; sb < n; sb++) {
            sum += re[sb] * syn_cos[j][sb] - im[sb] * syn_sin[j][sb];
        }
        st[j] = sum / n;
    }

    /* Pseudocode 15: extract interleaved samples into g[640] */
    float g[OBJCODING_QMF_LEN];
    for (int j = 0; j < flen / (2 * n); j++) {  /* j = 0..4 */
        for (int sb = 0; sb < n; sb++) {
            g[2 * n * j + sb]     = st[4 * n * j + sb];
            g[2 * n * j + n + sb] = st[4 * n * j + 3 * n + sb];
        }
    }

    /* Pseudocode 16: window */
    float w[OBJCODING_QMF_LEN];
    for (int j = 0; j < flen; j++)
        w[j] = g[j] * prot64[j];

    /* Pseudocode 17: fold and sum → 64 output samples */
    for (int ts = 0; ts < n; ts++) {
        float sum = 0;
        for (int j = 0; j < flen / n; j++)  /* j = 0..9 */
            sum += w[n * j + ts];
        pcm_out[ts] = sum;
    }
}
